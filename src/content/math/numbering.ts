export interface IndexedExercise extends ExerciseWithChapter { uid: number }

const dmExercises: ExerciseWithChapter[] = devoirs.flatMap((d) => {
  const chapter = chapters.find((c) => c.number === d.chapter) ?? chapters[0];
  return d.questions.map((q) => ({ ...q, chapter }));
});

const all = [...allExercises, ...dmExercises];
let next = Math.max(0, ...Object.values(REGISTRY)) + 1;
const numbers: Record<string, number> = { ...REGISTRY };
all.forEach((e) => { if (!numbers[e.id]) numbers[e.id] = next++; });

export const exerciseUid = (id: string) => numbers[id];
export const formatUid = (id: string) => (numbers[id] ? "#" + String(numbers[id]).padStart(3, "0") : "");
export const indexedExercises: IndexedExercise[] = all.map((e) => ({ ...e, uid: numbers[e.id] })).sort((a, b) => a.uid - b.uid);
export const getExerciseByUid = (uid: number) => indexedExercises.find((e) => e.uid === uid);
export const dmIdFor = (exerciseId: string) => devoirs.find((d) => d.questions.some((q) => q.id === exerciseId))?.id;

const strip = (s: string) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
export const searchExercises = (query: string, list: IndexedExercise[] = indexedExercises) => {
  const q = strip(query.trim()).replace(/^#/, "");
  if (!q) return list;
  if (/^\d+$/.test(q)) {
    const n = parseInt(q, 10);
    const exact = list.filter((e) => e.uid === n);
    if (exact.length) return exact;
  }
  const terms = q.split(/\s+/);
  return list.filter((e) => {
    const src = e.source === "cours" ? "cours" : e.source === "dm" ? "dm" : "td";
    const hay = strip(`${e.statement} ${e.chapter.title} chapitre ${e.chapter.number} chap ${e.chapter.number} ${src} exercice ${e.number}`);
    return terms.every((t) => hay.includes(t));
  });
};
